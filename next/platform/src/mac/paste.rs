//! Puts text into whatever has keyboard focus by pasting it. Per-character synthetic keystrokes
//! get dropped by web and Electron editors, while Cmd+V takes the same path as a real paste and
//! works everywhere. John's clipboard is snapshotted with every type it held (text, images,
//! files) and put back once the paste has landed.
//!
//! The dictation stays on this Mac and out of clipboard history: it sits on the clipboard for
//! 0.4 s only to be pasted, kept off Universal Clipboard and marked for clipboard managers to
//! skip.

use objc2::rc::Retained;
use objc2::AnyThread;
use objc2_app_kit::{NSPasteboard, NSPasteboardContentsOptions, NSPasteboardItem, NSPasteboardTypeString, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};
use std::ffi::c_void;
use std::time::Duration;

type CGEventRef = *mut c_void;

#[link(name = "CoreGraphics", kind = "framework")]
extern "C" {
    fn CGEventSourceCreate(state: i32) -> *mut c_void;
    fn CGEventCreateKeyboardEvent(source: *mut c_void, key: u16, down: bool) -> CGEventRef;
    fn CGEventSetFlags(event: CGEventRef, flags: u64);
    fn CGEventPost(tap: u32, event: CGEventRef);
}

#[link(name = "CoreFoundation", kind = "framework")]
extern "C" {
    fn CFRelease(cf: *const c_void);
}

const COMBINED_SESSION_STATE: i32 = 0;
const HID_EVENT_TAP: u32 = 0;
const KEY_V: u16 = 9;
const FLAG_COMMAND: u64 = 0x0010_0000;

/// The markers clipboard managers honour (nspasteboard.org): the content is short-lived and an
/// app put it there, so neither belongs in a history of what John copied.
const PRIVATE_TYPES: [&str; 2] = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];

/// One clipboard item: each type it held, and its data.
type Snapshot = Vec<Vec<(String, Vec<u8>)>>;

fn snapshot(pb: &NSPasteboard) -> Snapshot {
    let Some(items) = pb.pasteboardItems() else { return vec![] };
    items
        .iter()
        .map(|item| {
            item.types()
                .iter()
                .filter_map(|t| item.dataForType(&t).map(|d| (t.to_string(), d.to_vec())))
                .collect()
        })
        .collect()
}

fn restore(pb: &NSPasteboard, snap: &Snapshot) {
    pb.clearContents();
    let items: Vec<Retained<ProtocolObject>> = snap
        .iter()
        .map(|types| {
            let item = NSPasteboardItem::new();
            for (t, data) in types {
                item.setData_forType(&NSData::with_bytes(data), &NSString::from_str(t));
            }
            objc2::runtime::ProtocolObject::from_retained(item)
        })
        .collect();
    pb.writeObjects(&NSArray::from_retained_slice(&items));
}

type ProtocolObject = objc2::runtime::ProtocolObject<dyn NSPasteboardWriting>;

/// Puts `text` on the pasteboard kept off other devices and marked for clipboard managers to
/// skip. Returns the change count it left behind.
pub fn write_privately(text: &str, pb: &NSPasteboard) -> isize {
    pb.prepareForNewContentsWithOptions(NSPasteboardContentsOptions::CurrentHostOnly);
    let item = NSPasteboardItem::new();
    item.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
    for t in PRIVATE_TYPES {
        item.setData_forType(&NSData::new(), &NSString::from_str(t));
    }
    let objects = NSArray::from_retained_slice(&[objc2::runtime::ProtocolObject::from_retained(item) as Retained<ProtocolObject>]);
    pb.writeObjects(&objects);
    pb.changeCount()
}

fn command_v() {
    unsafe {
        let source = CGEventSourceCreate(COMBINED_SESSION_STATE);
        for down in [true, false] {
            let e = CGEventCreateKeyboardEvent(source, KEY_V, down);
            if e.is_null() {
                continue;
            }
            CGEventSetFlags(e, FLAG_COMMAND);
            CGEventPost(HID_EVENT_TAP, e);
            CFRelease(e);
        }
        if !source.is_null() {
            CFRelease(source);
        }
    }
}

/// Pastes `text` and puts John's clipboard back after `restore_after`, unless he copied
/// something else in the meantime.
pub fn paste(text: &str, restore_after: Duration) {
    if text.is_empty() {
        return;
    }
    let pb = NSPasteboard::generalPasteboard();
    let snap = snapshot(&pb);
    let ours = write_privately(text, &pb);
    command_v();
    if snap.is_empty() {
        return;
    }
    std::thread::spawn(move || {
        std::thread::sleep(restore_after);
        let pb = NSPasteboard::generalPasteboard();
        if pb.changeCount() == ours {
            restore(&pb, &snap);
        }
    });
}

/// Puts text on the clipboard the ordinary way: John asked to copy it, so it is his to keep.
pub fn copy(text: &str) {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
}

/// What the clipboard holds as text, for the selftest-style checks that never paste.
pub fn clipboard_text() -> Option<String> {
    let pb = NSPasteboard::generalPasteboard();
    pb.stringForType(unsafe { NSPasteboardTypeString }).map(|s| s.to_string())
}

#[allow(dead_code)]
fn _assert_any_thread() {
    // NSPasteboard is not main-thread-only, so paste and restore may run on any thread.
    let _ = NSPasteboardItem::alloc;
}
