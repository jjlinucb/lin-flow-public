import AppKit
import Foundation

/// Puts text into whatever has keyboard focus by pasting it. Per-character
/// synthetic keystrokes get dropped by web/Electron editors (ProseMirror,
/// Lexical...), while Cmd+V takes the same path as a real user paste and
/// works everywhere. The user's clipboard is snapshotted with every type it
/// held (text, images, files) and put back once the paste has landed.
///
/// The dictation itself stays on this Mac and out of clipboard history: it is on the clipboard
/// for 0.4 s only to be pasted, and it used to be ordinary content, free to reach John's iPhone
/// over Universal Clipboard and to land in any clipboard manager's history. What gets put back
/// afterwards is his own clipboard, restored exactly as it was.
public enum TextInjector {
    public static func paste(_ text: String, restoreAfter delay: TimeInterval = 0.4) {
        guard !text.isEmpty else { return }
        let pb = NSPasteboard.general
        let snapshot = pb.pasteboardItems?.map { item -> [NSPasteboard.PasteboardType: Data] in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let data = item.data(forType: t) { d[t] = data } }
            return d
        } ?? []

        let ourChange = writePrivately(text, to: pb)
        sendCommandV()

        guard !snapshot.isEmpty else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) {
            // If the user copied something else in the meantime, leave it.
            guard pb.changeCount == ourChange else { return }
            pb.clearContents()
            let items = snapshot.map { dict -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (t, data) in dict { item.setData(data, forType: t) }
                return item
            }
            pb.writeObjects(items)
        }
    }

    /// The markers clipboard managers honour (nspasteboard.org): the content is short-lived and
    /// an app put it there, so neither belongs in a history of what the user copied.
    public static let privateTypes = [NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
                                      NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")]

    /// Puts `text` on the pasteboard kept off other devices and marked for clipboard managers
    /// to skip. Returns the change count it left behind.
    @discardableResult
    public static func writePrivately(_ text: String, to pb: NSPasteboard) -> Int {
        pb.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for t in privateTypes { item.setData(Data(), forType: t) }
        pb.writeObjects([item])
        return pb.changeCount
    }

    static func sendCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false) else { return }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
    }
}
